# Tabbed Notes for Standard Notes (version 2.1)

OneNote-style tabs inside a single note. Each tab is a rich-text page that works like a Super note.

## Writing

- Type **/** to open the block menu: headings, lists, checklists, quotes, code blocks, tables, dividers, and images. Keep typing to filter, then press Enter.
- Markdown shortcuts work as you type: `# ` to `###### ` for headings, `- ` for bullets, `1. ` for numbers, `[] ` for a checklist, `> ` for a quote, ```` ``` ```` for code, `---` for a divider, and `**bold**`, `*italic*`, `~~strike~~`, `` `code` ``, `==highlight==`.
- Tab and Shift+Tab indent and outdent (and nest list items). In a table, Tab moves between cells.
- Select text and click the link button to add a link. Ctrl/Cmd+click a link to open it.
- Click inside a table to show the table button for adding or deleting rows and columns.
- Undo and redo are kept separately for each tab.
- Hover over a block and drag the handle that appears on its left to move it. (Not available on touch screens.)
- Type `/collapsible` (or use the **+** menu) to add a collapsible section. Click the arrow next to its title to open or close it. Backspace at the start of the title turns it back into normal text.
- Text uses Super's default font, size (15px on desktop, 16px on tablets, 18px on phones) and line spacing (1.5).

## Tabs

- Click **+** to add a tab. Double-click a tab (or press F2) to rename it.
- Right-click a tab (long-press on touch screens) to change its color, move it, or delete it.
- Drag tabs to reorder them. With a tab focused, the arrow keys move between tabs.

## Good to know

- **Super notes can be opened in Tabbed Notes.** If you switch a Super note's type to Tabbed Notes, its content goes into Tab 1. Collapsible sections, checklists, tables, and links come across intact. Broken structure, like the kind that made a Super note open blank, is repaired instead of failing. Nothing is saved until you edit.
- **Plain text and Markdown notes** come into Tab 1 with their formatting converted.
- **Your data is ordinary note text** (JSON), so it syncs, stays encrypted, appears in note history, and is included in backups.
- **Images** are inserted from a web address. Uploading image files isn't available to plugins.
- **Privacy:** the editor makes no network requests of its own. It only loads images you insert from web addresses.
